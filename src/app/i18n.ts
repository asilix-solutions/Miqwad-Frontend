export const SUPPORTED_LANGS = ["ar", "en"] as const;
export type SupportedLang = (typeof SUPPORTED_LANGS)[number];

const initialLang = (storage.get<SupportedLang>(StorageKeys.language) ?? "ar") as SupportedLang;

void i18n.use(initReactI18next).init({
  resources: {
    ar: { translation: ar },
    en: { translation: en },
  },
  lng: initialLang,
  fallbackLng: "ar",
  interpolation: { escapeValue: false },
});

/** Apply <html dir> + <html lang> on language change. */
function syncDocument(lang: SupportedLang): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

syncDocument(initialLang);

i18n.on("languageChanged", (lng) => {
  const next = (SUPPORTED_LANGS.includes(lng as SupportedLang) ? lng : "ar") as SupportedLang;
  storage.set(StorageKeys.language, next);
  syncDocument(next);
});

export default i18n;
